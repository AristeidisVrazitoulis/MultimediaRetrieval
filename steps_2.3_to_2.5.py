import open3d as o3d, numpy as np, plotly.graph_objects as go

def load_mesh(path):
    m = o3d.io.read_triangle_mesh(path)
    m.compute_vertex_normals()
    return m

def show(path, wireframe=False, axes=False):
    m = load_mesh(path)
    v, t = np.asarray(m.vertices), np.asarray(m.triangles)
    fig = go.Figure(go.Mesh3d(
        x=v[:,0], y=v[:,1], z=v[:,2], i=t[:,0], j=t[:,1], k=t[:,2],
        color='lightblue', flatshading=False))
    if wireframe:  # draw cell edges
        e = np.vstack([t[:,[0,1]], t[:,[1,2]], t[:,[2,0]]])
        e = np.unique(np.sort(e, axis=1), axis=0)
        xs, ys, zs = [], [], []
        for a, b in e:
            xs += [v[a,0], v[b,0], None]; ys += [v[a,1], v[b,1], None]; zs += [v[a,2], v[b,2], None]
        fig.add_trace(go.Scatter3d(x=xs, y=ys, z=zs, mode='lines',
                                   line=dict(color='black', width=1)))
    if axes:  # world axes
        for c, d in zip('rgb', np.eye(3)):
            fig.add_trace(go.Scatter3d(x=[0,d[0]], y=[0,d[1]], z=[0,d[2]],
                                       mode='lines', line=dict(color=c, width=5)))
    fig.update_layout(scene=dict(aspectmode='data'), width=900, height=650)
    fig.show()
    print(f"{len(v)} vertices, {len(t)} triangles")

