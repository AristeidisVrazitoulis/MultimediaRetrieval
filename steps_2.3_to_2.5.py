#meshing_surface_subdivision_midpoint() (to split every triangle into 4 smaller ones
#Checking after each subdivision if passed target_v (5000) passed -> no over-refining
def refine(path, out, target_v=5000):
    ms = pml.MeshSet(); ms.load_new_mesh(path)
    for _ in range(10):  #keep subdividing until we pass the target or not
        ms.meshing_surface_subdivision_midpoint()
        if ms.current_mesh().vertex_number() >= target_v:
            break
    ms.save_current_mesh(out)

#meshing_decimation_quadric_edge_collapse(targetfacenum=...) (repeatedly merges
#the edge whose removal changes the shape least until it hits the target
def simplify(path, out, target_v=8000):
    ms = pml.MeshSet()
    ms.load_new_mesh(path)
    ms.meshing_decimation_quadric_edge_collapse(targetfacenum=target_v * 2)
    ms.save_current_mesh(out)

